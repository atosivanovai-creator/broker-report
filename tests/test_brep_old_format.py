def test_old_format_reconciles():
    r = bp.parse_report(_report(), "acc_2021-10-01..2021-12-31.xls")
    f = r["flows"]
    assert (f["dep"], f["sec_in"], f["sec_out"], f["exch"], f["broker"], f["other"]) == (1000, 600, -500, -103.99, -10, 100)
    rec = bp.reconcile(r)
    assert {k: v for k, v in rec.items() if abs(v[2]) > 0.005} == {}, rec
    assert r["unknown"] == {}
    kinds = {i["comment"][:20]: i["kind"] for i in r["items"]}
    assert kinds["Вознаграждение по пу"] == bp.KIND_INTEREST          # проценты на остаток — доход, не ввод
    assert kinds["Счет списания: КлФ-0"] == bp.KIND_TR                 # перевод со своего счёта — не прибыль


def test_nontrade_kind_14_4_and_fee_correction():
    k = bp._nontrade_kind
    assert k("Зачисление ДС", "Коррекция вознаграждения по пункту 14.4 Регламента (НДФЛ за 2021 год у", 0.02) == bp.KIND_INTEREST
    assert k("Зачисление ДС", "Проценты по пункту 14.4 Регламента", 1) == bp.KIND_INTEREST
    assert k("Зачисление ДС", "", 1) == bp.KIND_IN                     # прочее зачисление — по-прежнему ввод
    assert k("Услуги сторонних организаций", "Коррекция комиссии за клиринг по сделкам", -1) == bp.KIND_EXCH
    assert k("Услуги сторонних организаций", "что-то иное", -1) == bp.KIND_OTHER


def test_transfer_out_reconciles_as_withdrawal():
    r = {"items": [{"kind": bp.KIND_TR, "amount": -500.0}], "flows": {"wd": 500.0}}
    assert bp.reconcile(r)["wd"] == (-500.0, -500.0, 0.0)
